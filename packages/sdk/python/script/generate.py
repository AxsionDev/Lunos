"""Generate the Python SDK's typed layer from the server's OpenAPI spec.

The same spec the JavaScript SDK is generated from (``packages/sdk/openapi.json``, written by
``script/generate.ts``). It writes:

- ``src/lunos/_generated/models.py``: pydantic models for every schema (datamodel-code-generator);
- ``src/lunos/_generated/operations.py``: a sync and an async method for every operation, grouped
  by operation id like the JavaScript SDK (``session.create`` -> ``client.api.session.create``);
- ``src/lunos/_version.py``: the SDK version, which tracks the Lunos version the spec came from.

Run it with ``uv run --group codegen python script/generate.py`` (``--check`` fails on drift).
"""

from __future__ import annotations

import json
import keyword
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[2]
SPEC = REPO / "packages" / "sdk" / "openapi.json"
OUT = ROOT / "src" / "lunos" / "_generated"
HEADER = "# Generated by packages/sdk/python/script/generate.py from packages/sdk/openapi.json. Do not edit.\n"


def main() -> None:
    check = "--check" in sys.argv
    spec = sanitize(json.loads(SPEC.read_text(encoding="utf-8")))
    files = {
        OUT / "models.py": models(spec),
        OUT / "operations.py": operations(spec),
        OUT / "__init__.py": HEADER,
        ROOT / "src" / "lunos" / "_version.py": version(),
    }
    stale = [path for path, text in files.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    if check:
        if stale:
            sys.exit("out of date, run script/generate.py: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        print("generated files are up to date")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_text(files[path], encoding="utf-8")
        print("wrote", path.relative_to(ROOT))


def sanitize(spec: dict) -> dict:
    """Schema names like ``Event.tui.toast.show`` aren't Python identifiers; rename them."""
    schemas = spec["components"]["schemas"]
    renamed = {name: re.sub(r"[^A-Za-z0-9_]", "_", name) for name in schemas}
    text = json.dumps(spec)
    for old, new in renamed.items():
        if old != new:
            text = text.replace(f'"#/components/schemas/{old}"', f'"#/components/schemas/{new}"')
    spec = json.loads(text)
    spec["components"]["schemas"] = {renamed[k]: v for k, v in spec["components"]["schemas"].items()}
    return spec


def models(spec: dict) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        source = Path(tmp) / "spec.json"
        target = Path(tmp) / "models.py"
        source.write_text(json.dumps(spec), encoding="utf-8")
        subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                "--input",
                str(source),
                "--input-file-type",
                "openapi",
                "--output",
                str(target),
                "--output-model-type",
                "pydantic_v2.BaseModel",
                "--target-python-version",
                "3.10",
                "--use-annotated",
                "--field-constraints",
                "--use-standard-collections",
                "--use-union-operator",
                "--use-schema-description",
                "--enum-field-as-literal",
                "all",
                "--allow-extra-fields",
                "--disable-timestamp",
                "--custom-file-header",
                HEADER.strip(),
            ],
            check=True,
        )
        return target.read_text(encoding="utf-8")


def snake(name: str) -> str:
    name = re.sub(r"[^A-Za-z0-9]+", "_", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name).lower().strip("_")
    return name + "_" if keyword.iskeyword(name) or name in {"self", "body"} else name


def pascal(parts: list[str]) -> str:
    return "".join(p[:1].upper() + p[1:] for part in parts for p in re.split(r"[^A-Za-z0-9]+", part) if p)


def ref_name(schema: dict | None) -> str | None:
    if schema and "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    return None


def returns(op: dict) -> tuple[str, str]:
    """The method's return annotation and the response kind: json model, list of models, raw, sse."""
    for code, response in op.get("responses", {}).items():
        if not code.startswith("2"):
            continue
        content = response.get("content", {})
        if "text/event-stream" in content:
            return "sse", ""
        if "application/json" in content:
            schema = content["application/json"].get("schema", {})
            name = ref_name(schema)
            if name:
                return "model", name
            item = ref_name(schema.get("items")) if schema.get("type") == "array" else None
            if item:
                return "list", item
            return "json", ""
        if content:
            return "bytes", ""
    return "json", ""


def operations(spec: dict) -> str:
    tree: dict = {}
    for path, methods in spec["paths"].items():
        for method, op in methods.items():
            if not isinstance(op, dict) or "operationId" not in op:
                continue
            *groups, leaf = op["operationId"].split(".")
            node = tree
            for group in groups:
                node = node.setdefault(group, {})
            node.setdefault("__ops__", []).append((snake(leaf), method.upper(), path, op))

    out = [
        HEADER,
        '"""Every server operation, as a typed method. Use ``client.api`` (see ``lunos.Lunos``)."""\n',
        "from __future__ import annotations\n",
        "from collections.abc import AsyncIterator, Iterator",
        "from typing import TYPE_CHECKING, Any\n",
        "from .._http import AsyncTransport, SyncTransport, validate\n",
        "if TYPE_CHECKING:",
        "    from . import models\n",
    ]
    for is_async in (True, False):
        emit(out, tree, ["Async" if is_async else "Sync"], is_async)
    return "\n".join(out) + "\n"


def emit(out: list[str], node: dict, name: list[str], is_async: bool) -> str:
    cls = pascal(name) + "API" if len(name) > 1 else ("AsyncAPI" if is_async else "SyncAPI")
    children = {key: value for key, value in node.items() if key != "__ops__"}
    # An operation and a group with the same name (``vcs.diff`` and ``vcs.diff.raw``): the group's
    # operations join this class as ``diff_raw``.
    leaves = {op[0] for op in node.get("__ops__", [])}
    for key in [k for k in children if snake(k) in leaves]:
        clash = children.pop(key)
        if set(clash) != {"__ops__"}:
            raise SystemExit(f"can't merge nested group {'.'.join([*name[1:], key])}")
        node = {**node, "__ops__": [*node["__ops__"], *((f"{snake(key)}_{n}", *rest) for n, *rest in clash["__ops__"])]}
    child_classes = {key: emit(out, value, [*name, key], is_async) for key, value in children.items()}
    transport = "AsyncTransport" if is_async else "SyncTransport"
    lines = [f"class {cls}:", f'    """Operations under ``{".".join(name[1:]) or "the server"}``."""\n']
    lines.append(f"    def __init__(self, transport: {transport}) -> None:")
    lines.append("        self._t = transport")
    for key, child in child_classes.items():
        lines.append(f"        self.{snake(key)} = {child}(transport)")
    lines.append("")
    for method_name, method, path, op in node.get("__ops__", []):
        lines.extend(operation(method_name, method, path, op, is_async))
    out.extend(lines)
    out.append("")
    return cls


def operation(method_name: str, method: str, path: str, op: dict, is_async: bool) -> list[str]:
    params = [p for p in op.get("parameters", []) if p["in"] in ("path", "query")]
    path_params = [p for p in params if p["in"] == "path"]
    query_params = [p for p in params if p["in"] == "query"]
    wildcard = path.endswith("/*")
    body_schema = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
    body_required = op.get("requestBody", {}).get("required", False) or bool(
        body_schema and body_schema.get("required")
    )
    kind, model = returns(op)

    args = ["self"]
    for p in path_params:
        args.append(f"{snake(p['name'])}: str")
    if wildcard:
        args.append("path: str")
    if body_schema is not None:
        body_type = f"models.{ref_name(body_schema)} | dict[str, Any]" if ref_name(body_schema) else "dict[str, Any]"
        args.append(f"body: {body_type}" if body_required else f"body: {body_type} | None = None")
    keyword_only = [f"{snake(p['name'])}: Any = None" for p in query_params if not p.get("required")]
    required_query = [f"{snake(p['name'])}: Any" for p in query_params if p.get("required")]
    if required_query or keyword_only:
        args.append("*")
        args.extend(required_query + keyword_only)
    args.append("timeout: float | None = None")

    if kind == "sse":
        ret = "AsyncIterator[dict[str, Any]]" if is_async else "Iterator[dict[str, Any]]"
    elif kind == "model":
        ret = f"models.{model}"
    elif kind == "list":
        ret = f"list[models.{model}]"
    elif kind == "bytes":
        ret = "bytes"
    else:
        ret = "Any"

    fmt = path[:-2] + "/{path}" if wildcard else path
    fmt_args = ", ".join(f"{p['name']}={snake(p['name'])}" for p in path_params)
    if wildcard:
        fmt_args = ", ".join(filter(None, [fmt_args, "path=path"]))
    url = f'"{fmt}".format({fmt_args})' if fmt_args else f'"{fmt}"'
    query = "{" + ", ".join(f'"{p["name"]}": {snake(p["name"])}' for p in query_params) + "}"
    summary = (op.get("summary") or op.get("description") or op["operationId"]).strip().splitlines()[0]
    doc = f'        """{summary.replace(chr(34) * 3, "")} (``{method} {path}``, ``{op["operationId"]}``)."""'

    if kind == "sse":
        prefix = "def"
        call = f"return self._t.sse({url}, params={query}, timeout=timeout)"
    else:
        prefix = "async def" if is_async else "def"
        aw = "await " if is_async else ""
        body = "body" if body_schema is not None else "None"
        raw = "True" if kind == "bytes" else "False"
        call = f"data = {aw}self._t.request({method!r}, {url}, params={query}, json={body}, timeout=timeout, raw={raw})"
    lines = [f"    {prefix} {method_name}({', '.join(args)}) -> {ret}:", doc, f"        {call}"]
    if kind == "model":
        lines.append(f'        return validate("{model}", data)')
    elif kind == "list":
        lines.append(f'        return validate("{model}", data, many=True)')
    elif kind != "sse":
        lines.append("        return data")
    lines.append("")
    return lines


def version() -> str:
    lunos = json.loads((REPO / "packages" / "opencode" / "package.json").read_text(encoding="utf-8"))["version"]
    return (
        HEADER
        + "# The SDK's version is the Lunos version whose API it was generated from (XCOD-337).\n"
        + f'__version__ = "{lunos}"\n'
        + f'API_VERSION = "{lunos}"\n'
    )


if __name__ == "__main__":
    main()
